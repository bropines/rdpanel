-- Relays: the co-located hbbr ("local"), unmanaged third-party relays
-- ("static") and remote hbbr hosts driven by `rdpanel agent` ("agent").
-- hbbs' relay list (admin `rs`) is computed from this table: healthy relays,
-- each repeated `weight` times (hbbs picks relays round-robin and keeps
-- duplicates). See docs/design/relay-agents.md and docs/relay-agents.md.
--
-- Data migration: every entry of server_settings('hbbs','relay_servers')
-- becomes a static relay and the row is removed (relay_servers is computed
-- from now on). The local relay is seeded at runtime from
-- RDPANEL_HBBS_RELAY_PUBLIC_HOST / RELAY. Down restores the static list.

-- +goose Up
CREATE TABLE relays (
    id               BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             TEXT    NOT NULL UNIQUE CHECK (length(name) BETWEEN 1 AND 64),
    kind             TEXT    NOT NULL CHECK (kind IN ('local', 'agent', 'static')),
    -- host[:port] handed to clients through hbbs; no commas or spaces (it
    -- ends up in a comma-separated admin command).
    public_host      TEXT    NOT NULL CHECK (length(public_host) BETWEEN 1 AND 255
                                             AND strpos(public_host, ',') = 0 AND strpos(public_host, ' ') = 0),
    region           TEXT    NULL CHECK (region IS NULL OR length(region) <= 32),
    weight           BIGINT  NOT NULL DEFAULT 1 CHECK (weight BETWEEN 0 AND 5),
    in_rotation      BIGINT  NOT NULL DEFAULT 1 CHECK (in_rotation IN (0, 1)),
    admin_state      TEXT    NOT NULL DEFAULT 'enabled' CHECK (admin_state IN ('enabled', 'draining', 'disabled')),
    health           TEXT    NOT NULL DEFAULT 'pending' CHECK (health IN ('pending', 'active', 'degraded', 'offline')),
    health_since     BIGINT  NULL,
    last_probe_at    BIGINT  NULL,
    last_probe_ms    DOUBLE PRECISION NULL,
    last_probe_error TEXT    NULL,
    created_by       BIGINT  NULL REFERENCES users (id) ON DELETE SET NULL,
    created_at       BIGINT  NOT NULL,
    updated_at       BIGINT  NOT NULL
);
-- At most one co-located relay.
CREATE UNIQUE INDEX ux_relays_local ON relays (kind) WHERE kind = 'local';

-- 1:1 with relays.kind = 'agent'.
CREATE TABLE relay_agents (
    relay_id          BIGINT  PRIMARY KEY REFERENCES relays (id) ON DELETE CASCADE,
    -- sha256 of the one-time enrollment token (never the token itself).
    enroll_token_hash BYTEA   NULL CHECK (enroll_token_hash IS NULL OR length(enroll_token_hash) = 32),
    enroll_expires_at BIGINT  NULL,
    require_approval  BIGINT  NOT NULL DEFAULT 1 CHECK (require_approval IN (0, 1)),
    -- ed25519 public key generated by the agent at enrollment.
    agent_pubkey      BYTEA   NULL CHECK (agent_pubkey IS NULL OR length(agent_pubkey) = 32),
    enrolled_at       BIGINT  NULL,
    enrolled_from_ip  TEXT    NULL,
    approved_at       BIGINT  NULL,
    approved_by       BIGINT  NULL REFERENCES users (id) ON DELETE SET NULL,
    revoked_at        BIGINT  NULL,
    hostname          TEXT    NULL,
    agent_version     TEXT    NULL,
    hbbr_version      TEXT    NULL,
    arch              TEXT    NULL,
    -- Effective config bookkeeping: desired_version is bumped whenever the
    -- sha256 of the effective config (config_hash) changes.
    desired_version   BIGINT  NOT NULL DEFAULT 0,
    desired_at        BIGINT  NULL,
    config_hash       TEXT    NULL,
    acked_version     BIGINT  NOT NULL DEFAULT 0,
    acked_at          BIGINT  NULL,
    -- Per-key apply errors of the last ACK (JSON object key -> message).
    ack_errors        TEXT    NULL,
    last_seen_at      BIGINT  NULL,
    last_status       TEXT    NULL
);
CREATE UNIQUE INDEX ux_relay_agents_pubkey ON relay_agents (agent_pubkey) WHERE agent_pubkey IS NOT NULL;
CREATE UNIQUE INDEX ux_relay_agents_token ON relay_agents (enroll_token_hash) WHERE enroll_token_hash IS NOT NULL;

-- Per-relay overrides of hbbr keys (same keys and JSON values as
-- server_settings target='hbbr', which is the global relay profile).
CREATE TABLE relay_settings (
    relay_id   BIGINT  NOT NULL REFERENCES relays (id) ON DELETE CASCADE,
    key        TEXT    NOT NULL CHECK (length(key) BETWEEN 1 AND 64),
    value      TEXT    NOT NULL,
    updated_by BIGINT  NULL REFERENCES users (id) ON DELETE SET NULL,
    updated_at BIGINT  NOT NULL,
    PRIMARY KEY (relay_id, key)
);

-- Existing admin-typed relay list -> static relays (they were in rotation,
-- so they start "active"; the prober takes them out after 3 failures).
WITH src AS (
    SELECT value::jsonb AS v, updated_at FROM server_settings
    WHERE target = 'hbbs' AND key = 'relay_servers'
), items AS (
    SELECT j.value #>> '{}' AS host, j.ord, src.updated_at
    FROM src, jsonb_array_elements(CASE WHEN jsonb_typeof(src.v) = 'array' THEN src.v ELSE '[]' END)
        WITH ORDINALITY AS j (value, ord)
    WHERE jsonb_typeof(j.value) = 'string'
)
INSERT INTO relays (name, kind, public_host, weight, in_rotation, admin_state, health, created_at, updated_at)
SELECT substr(host, 1, 64), 'static', host, 1, 1, 'enabled', 'active', min(updated_at), min(updated_at)
FROM items
WHERE length(host) BETWEEN 1 AND 255 AND strpos(host, ',') = 0 AND strpos(host, ' ') = 0
GROUP BY host
ORDER BY min(ord)
ON CONFLICT DO NOTHING;

DELETE FROM server_settings WHERE target = 'hbbs' AND key = 'relay_servers';

-- +goose Down
INSERT INTO server_settings (target, key, value, updated_at)
SELECT 'hbbs', 'relay_servers', '[' || string_agg(to_json(public_host)::text, ',' ORDER BY first_id) || ']',
    (extract(epoch FROM now()) * 1000)::bigint
FROM (SELECT public_host, min(id) AS first_id FROM relays
      WHERE kind IN ('local', 'static') AND admin_state = 'enabled' GROUP BY public_host) t
HAVING count(*) > 0
ON CONFLICT (target, key) DO UPDATE SET value = excluded.value, updated_by = NULL,
    updated_at = excluded.updated_at, applied_at = NULL, last_error = NULL;

DROP TABLE relay_settings;
DROP TABLE relay_agents;
DROP TABLE relays;
