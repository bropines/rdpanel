-- Schema v1, part 1: users, groups, credentials, tokens, identity providers.
--
-- PostgreSQL mirror of migrations/00001_identity.sql. The two schemas must
-- stay equivalent: repositories run the same SQL on both (internal/db adapts
-- placeholders, LIKE and booleans at run time).
--
-- Conventions (see docs/schema.md):
--   * timestamps are BIGINT unix milliseconds, UTC;
--   * every SQLite INTEGER is BIGINT, including booleans (0/1 with CHECK) so
--     the Go code binds and scans the same values on both engines;
--   * BLOB is BYTEA, REAL is DOUBLE PRECISION;
--   * enums are TEXT with CHECK; JSON is TEXT (validated by the application;
--     SQLite's json_valid CHECKs have no cheap equivalent);
--   * AUTOINCREMENT ids are identity columns (ids are never reused); after
--     inserting explicit ids, db.SyncIDSequence moves the sequence on;
--   * SQLite NOCASE columns are CITEXT; the "nocase" ICU collation below keeps
--     "COLLATE NOCASE" in queries and indexes working unchanged.

-- +goose Up

CREATE EXTENSION IF NOT EXISTS citext;
-- Case-insensitive (ICU strength 2), accent-sensitive, like SQLite NOCASE for
-- ASCII. Nondeterministic, so never a column collation (PostgreSQL < 18
-- rejects LIKE on such columns): NOCASE columns are CITEXT instead.
CREATE COLLATION IF NOT EXISTS nocase (provider = icu, locale = 'und-u-ks-level2', deterministic = false);

CREATE TABLE user_groups (
    id          BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT    NOT NULL CHECK (length(name) BETWEEN 1 AND 128),
    -- self: members see only their own devices; shared: members see each
    -- other's devices/users in the client ("Share group", legacy type 2).
    visibility  TEXT    NOT NULL DEFAULT 'self' CHECK (visibility IN ('self', 'shared')),
    note        TEXT    NOT NULL DEFAULT '',
    created_at  BIGINT  NOT NULL,
    updated_at  BIGINT  NOT NULL
);
CREATE UNIQUE INDEX ux_user_groups_name ON user_groups (name COLLATE nocase);

CREATE TABLE users (
    -- Must fit u32: embedded in client JWTs verified by hbbs (Claims.user_id: u32).
    id                  BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 4294967295),
    username            CITEXT  NOT NULL CHECK (length(username) BETWEEN 1 AND 128),
    email               CITEXT  NULL,
    display_name        TEXT    NOT NULL DEFAULT '',
    avatar_url          TEXT    NOT NULL DEFAULT '',
    note                TEXT    NOT NULL DEFAULT '',
    -- NULL hash = no local password (OIDC-only / legacy empty password).
    password_hash       TEXT    NULL CHECK (password_hash IS NULL OR length(password_hash) > 0),
    password_algo       TEXT    NULL CHECK (password_algo IN ('bcrypt', 'legacy_md5_rustdesk_api', 'argon2id')),
    role                TEXT    NOT NULL DEFAULT 'user' CHECK (role IN ('admin', 'user')),
    status              TEXT    NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    -- NULL = no group (behaves like a 'self' group).
    user_group_id       BIGINT  NULL REFERENCES user_groups (id) ON DELETE SET NULL,
    -- Admin-forced: the user must enrol TOTP before using the panel.
    totp_required       BIGINT  NOT NULL DEFAULT 0 CHECK (totp_required IN (0, 1)),
    password_changed_at BIGINT  NULL,
    last_login_at       BIGINT  NULL,
    created_at          BIGINT  NOT NULL,
    updated_at          BIGINT  NOT NULL,
    CHECK ((password_hash IS NULL) = (password_algo IS NULL))
);
CREATE UNIQUE INDEX ux_users_username ON users (username);
CREATE INDEX ix_users_email ON users (email) WHERE email IS NOT NULL;
CREATE INDEX ix_users_user_group_id ON users (user_group_id);

-- Client tokens (RustDesk app, HS256 JWT) and panel sessions (opaque cookie
-- token). Only sha256(token) is stored.
CREATE TABLE auth_tokens (
    id                  BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT  NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    kind                TEXT    NOT NULL CHECK (kind IN ('client', 'web')),
    token_sha256        BYTEA   NOT NULL CHECK (length(token_sha256) = 32),
    -- client: fixed JWT "exp" (what hbbs sees); NULL for web/non-JWT tokens.
    jwt_expires_at      BIGINT  NULL,
    -- client: sliding expiry; web: idle expiry. Extended on use.
    expires_at          BIGINT  NOT NULL,
    -- web: hard cap regardless of activity.
    absolute_expires_at BIGINT  NULL,
    device_rustdesk_id  TEXT    NULL,
    device_uuid         TEXT    NULL,
    client_platform     TEXT    NULL,
    user_agent          TEXT    NULL,
    ip                  TEXT    NULL,
    -- web: sessions created by a password login that still owe a TOTP step.
    mfa_pending         BIGINT  NOT NULL DEFAULT 0 CHECK (mfa_pending IN (0, 1)),
    created_at          BIGINT  NOT NULL,
    last_used_at        BIGINT  NULL,
    revoked_at          BIGINT  NULL,
    revoke_reason       TEXT    NULL,
    legacy_id           BIGINT  NULL
);
CREATE UNIQUE INDEX ux_auth_tokens_token_sha256 ON auth_tokens (token_sha256);
CREATE INDEX ix_auth_tokens_user_kind ON auth_tokens (user_id, kind);
CREATE INDEX ix_auth_tokens_device_uuid ON auth_tokens (device_uuid) WHERE device_uuid IS NOT NULL;
CREATE INDEX ix_auth_tokens_expires_at ON auth_tokens (expires_at);

CREATE TABLE identity_providers (
    id                     BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Legacy "op": the client sees "oidc/<slug>"; user_identities key on it.
    slug                   TEXT    NOT NULL CHECK (length(slug) BETWEEN 1 AND 64),
    kind                   TEXT    NOT NULL CHECK (kind IN ('github', 'google', 'oidc', 'linuxdo')),
    display_name           TEXT    NOT NULL DEFAULT '',
    client_id              TEXT    NOT NULL DEFAULT '',
    client_secret_enc      BYTEA   NULL,
    issuer                 TEXT    NULL,
    scopes                 TEXT    NOT NULL DEFAULT '[]',
    pkce_enabled           BIGINT  NOT NULL DEFAULT 1 CHECK (pkce_enabled IN (0, 1)),
    pkce_method            TEXT    NOT NULL DEFAULT 'S256' CHECK (pkce_method IN ('S256', 'plain')),
    auto_register          BIGINT  NOT NULL DEFAULT 0 CHECK (auto_register IN (0, 1)),
    -- Link to an existing local user by email only if the IdP says email_verified.
    link_by_verified_email BIGINT  NOT NULL DEFAULT 0 CHECK (link_by_verified_email IN (0, 1)),
    enabled                BIGINT  NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
    sort_order             BIGINT  NOT NULL DEFAULT 0,
    created_at             BIGINT  NOT NULL,
    updated_at             BIGINT  NOT NULL
);
CREATE UNIQUE INDEX ux_identity_providers_slug ON identity_providers (slug);

CREATE TABLE user_identities (
    id              BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT  NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    provider_id     BIGINT  NOT NULL REFERENCES identity_providers (id) ON DELETE CASCADE,
    -- Provider subject (OIDC sub, GitHub numeric id). Legacy open_id verbatim.
    subject         TEXT    NOT NULL CHECK (length(subject) > 0),
    email           TEXT    NULL,
    email_verified  BIGINT  NOT NULL DEFAULT 0 CHECK (email_verified IN (0, 1)),
    display_name    TEXT    NOT NULL DEFAULT '',
    username        TEXT    NOT NULL DEFAULT '',
    avatar_url      TEXT    NOT NULL DEFAULT '',
    legacy_union_id TEXT    NULL,
    last_login_at   BIGINT  NULL,
    created_at      BIGINT  NOT NULL,
    updated_at      BIGINT  NOT NULL
);
CREATE UNIQUE INDEX ux_user_identities_provider_subject ON user_identities (provider_id, subject);
CREATE INDEX ix_user_identities_user_id ON user_identities (user_id);

-- OAuth/OIDC login state (client "code" polling, panel login, account bind,
-- webauth). Replaces the legacy in-memory map; 5 minute TTL.
CREATE TABLE oauth_states (
    id                  BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- sha256 of the state value (also the client's poll "code").
    state_sha256        BYTEA   NOT NULL CHECK (length(state_sha256) = 32),
    action              TEXT    NOT NULL CHECK (action IN ('login', 'bind', 'webauth')),
    flow                TEXT    NOT NULL CHECK (flow IN ('client', 'web')),
    -- NULL only for webauth (approval via panel session, no IdP).
    provider_id         BIGINT  NULL REFERENCES identity_providers (id) ON DELETE CASCADE,
    pkce_verifier_enc   BYTEA   NULL,
    nonce               TEXT    NULL,
    -- Requesting device: auth-query must present the same id/uuid.
    device_rustdesk_id  TEXT    NULL,
    device_uuid         TEXT    NULL,
    device_name         TEXT    NULL,
    device_os           TEXT    NULL,
    device_type         TEXT    NULL,
    redirect_path       TEXT    NULL,
    -- bind: the panel user initiating the link.
    initiator_user_id   BIGINT  NULL REFERENCES users (id) ON DELETE CASCADE,
    -- Set by the callback / webauth approval; consumed by the poll.
    result_user_id      BIGINT  NULL REFERENCES users (id) ON DELETE CASCADE,
    result_error        TEXT    NULL,
    -- Pending-bind IdP profile (JSON) when auto-register is off.
    profile_json        TEXT    NULL,
    consumed_at         BIGINT  NULL,
    created_at          BIGINT  NOT NULL,
    expires_at          BIGINT  NOT NULL
);
CREATE UNIQUE INDEX ux_oauth_states_state_sha256 ON oauth_states (state_sha256);
CREATE INDEX ix_oauth_states_expires_at ON oauth_states (expires_at);

CREATE TABLE totp_secrets (
    user_id        BIGINT  PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    -- AEAD(secret) with associated data "totp:<user_id>".
    secret_enc     BYTEA   NOT NULL,
    -- NULL while enrolment is unconfirmed.
    confirmed_at   BIGINT  NULL,
    -- Last accepted 30 s step; codes at or before it are rejected (replay).
    last_used_step BIGINT  NULL,
    created_at     BIGINT  NOT NULL,
    updated_at     BIGINT  NOT NULL
);

CREATE TABLE recovery_codes (
    id          BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT  NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    code_sha256 BYTEA   NOT NULL CHECK (length(code_sha256) = 32),
    used_at     BIGINT  NULL,
    created_at  BIGINT  NOT NULL
);
CREATE UNIQUE INDEX ux_recovery_codes_user_code ON recovery_codes (user_id, code_sha256);

-- +goose Down
DROP TABLE recovery_codes;
DROP TABLE totp_secrets;
DROP TABLE oauth_states;
DROP TABLE user_identities;
DROP TABLE identity_providers;
DROP TABLE auth_tokens;
DROP TABLE users;
DROP TABLE user_groups;
DROP COLLATION IF EXISTS nocase;
