-- Public "connect to this server" links (/s/<token>): anyone with the link
-- gets the official RustDesk client preconfigured for this server and its
-- connection settings, without signing in. Only sha256 of the token is used
-- for lookups; token_enc keeps the token sealed with the panel AEAD (AD
-- "server_share_link.token:<id>") so its creator can copy the link again.
-- (share_links is the unrelated legacy web-client device share table.)
-- Regular users may create links only when their user group allows it.

-- +goose Up
CREATE TABLE server_share_links (
    id            BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT  NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    label         TEXT    NOT NULL DEFAULT '' CHECK (length(label) <= 64),
    token_sha256  BYTEA   NOT NULL UNIQUE CHECK (length(token_sha256) = 32),
    -- Written right after the insert (the AD contains the row id).
    token_enc     BYTEA   NULL,
    -- NULL = permanent (until revoked).
    expires_at    BIGINT  NULL,
    -- NULL = unlimited installer downloads.
    max_downloads BIGINT  NULL CHECK (max_downloads IS NULL OR max_downloads > 0),
    views         BIGINT  NOT NULL DEFAULT 0,
    downloads     BIGINT  NOT NULL DEFAULT 0,
    last_used_at  BIGINT  NULL,
    created_at    BIGINT  NOT NULL,
    revoked_at    BIGINT  NULL
);
CREATE INDEX ix_server_share_links_user ON server_share_links (user_id, created_at);

ALTER TABLE user_groups ADD COLUMN can_share_links BIGINT NOT NULL DEFAULT 0 CHECK (can_share_links IN (0, 1));

-- +goose Down
ALTER TABLE user_groups DROP COLUMN can_share_links;
DROP TABLE server_share_links;
